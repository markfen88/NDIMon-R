TextBitmap TextRenderer::render_fallback(const std::string& text, int px_height) {
    TextBitmap bm;
    int scale = std::max(1, px_height / 8);
    if (text.empty()) return bm;
    bm.w = (int)text.size() * 8 * scale;
    bm.h = 8 * scale;
    bm.baseline = 7 * scale;
    bm.alpha.assign((size_t)bm.w * bm.h, 0);
    for (size_t i = 0; i < text.size(); i++) {
        unsigned char ch = (unsigned char)text[i];
        if (ch < 32 || ch > 127) ch = '?';
        const uint8_t* glyph = kFont8x8[ch - 32];
        for (int row = 0; row < 8; row++)
            for (int col = 0; col < 8; col++) {
                if (!(glyph[row] & (1u << col))) continue;
                for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++) {
                        int px = (int)i * 8 * scale + col * scale + sx;
                        int py = row * scale + sy;
                        bm.alpha[(size_t)py * bm.w + px] = 255;
                    }
            }
    }
    return bm;
}

// ---------------------------------------------------------------------------
// TrueType face
// ---------------------------------------------------------------------------
struct TextRenderer::Face {
    std::vector<unsigned char> data;
    stbtt_fontinfo info{};
    bool ok = false;

    bool load(const std::string& path) {
        std::ifstream f(path, std::ios::binary);
        if (!f) return false;
        data.assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
        if (data.empty()) return false;
        int off = stbtt_GetFontOffsetForIndex(data.data(), 0);
        ok = off >= 0 && stbtt_InitFont(&info, data.data(), off) != 0;
        return ok;
    }
};

TextRenderer::TextRenderer() = default;
TextRenderer::~TextRenderer() = default;

bool TextRenderer::load(const std::string& regular_path, const std::string& semibold_path) {
    regular_.reset();
    semibold_.reset();
    auto r = std::make_unique<Face>();
    if (!r->load(regular_path)) return false;
    regular_ = std::move(r);
    if (!semibold_path.empty()) {
        auto b = std::make_unique<Face>();
        if (b->load(semibold_path)) semibold_ = std::move(b);
    }
    return true;
}

bool TextRenderer::loaded() const { return regular_ != nullptr; }

// Latin-1 bytes map 1:1 to code points; anything else becomes '?'.
static int codepoint_at(const std::string& s, size_t i) {
    unsigned char c = (unsigned char)s[i];
    return (c < 32 && c != '\t') ? '?' : (int)c;
}

namespace {
struct Layout {
    float scale = 0; int ascent = 0, descent = 0, line_gap = 0;
    int width = 0;   // total advance in pixels
};
}

static Layout layout_line(const stbtt_fontinfo& info, const std::string& text, int px_height) {
    Layout l;
    l.scale = stbtt_ScaleForPixelHeight(&info, (float)px_height);
    stbtt_GetFontVMetrics(&info, &l.ascent, &l.descent, &l.line_gap);
    float x = 0;
    for (size_t i = 0; i < text.size(); i++) {
        int cp = codepoint_at(text, i);
        int adv = 0, lsb = 0;
        stbtt_GetCodepointHMetrics(&info, cp, &adv, &lsb);
        x += adv * l.scale;
        if (i + 1 < text.size())
            x += stbtt_GetCodepointKernAdvance(&info, cp, codepoint_at(text, i + 1)) * l.scale;
    }
    l.width = (int)std::ceil(x) + 2;  // +2: room for the last glyph's right-side overhang
    return l;
}

int TextRenderer::measure(const std::string& text, int px_height, bool semibold) const {
    if (text.empty()) return 0;
    const Face* face = (semibold && semibold_) ? semibold_.get() : regular_.get();
    if (!face) return render_fallback(text, px_height).w;
    return layout_line(face->info, text, px_height).width;
}

TextBitmap TextRenderer::render(const std::string& text, int px_height, bool semibold) const {
    TextBitmap bm;
    if (text.empty() || px_height < 4) return bm;
    const Face* face = (semibold && semibold_) ? semibold_.get() : regular_.get();
    if (!face) return render_fallback(text, px_height);

    const stbtt_fontinfo& info = face->info;
    Layout l = layout_line(info, text, px_height);
    int ascent_px  = (int)std::ceil(l.ascent * l.scale);
    int descent_px = (int)std::ceil(-l.descent * l.scale);
    bm.w = l.width;
    bm.h = ascent_px + descent_px;
    bm.baseline = ascent_px;
    bm.alpha.assign((size_t)bm.w * bm.h, 0);

    float x = 0;
    for (size_t i = 0; i < text.size(); i++) {
        int cp = codepoint_at(text, i);
        int adv = 0, lsb = 0;
        stbtt_GetCodepointHMetrics(&info, cp, &adv, &lsb);
        float x_shift = x - std::floor(x);
        int x0, y0, x1, y1;
        stbtt_GetCodepointBitmapBoxSubpixel(&info, cp, l.scale, l.scale, x_shift, 0, &x0, &y0, &x1, &y1);
        int gw = x1 - x0, gh = y1 - y0;
        if (gw > 0 && gh > 0) {
            int ox = (int)std::floor(x) + x0;
            int oy = bm.baseline + y0;
            // Render into a scratch box then clip into the line bitmap.
            std::vector<unsigned char> g((size_t)gw * gh);
            stbtt_MakeCodepointBitmapSubpixel(&info, g.data(), gw, gh, gw, l.scale, l.scale, x_shift, 0, cp);
            for (int gy = 0; gy < gh; gy++) {
                int py = oy + gy;
                if (py < 0 || py >= bm.h) continue;
                for (int gx = 0; gx < gw; gx++) {
                    int px = ox + gx;
                    if (px < 0 || px >= bm.w) continue;
                    uint8_t& dst = bm.alpha[(size_t)py * bm.w + px];
                    dst = (uint8_t)std::max<int>(dst, g[(size_t)gy * gw + gx]);
                }
            }
        }
        x += adv * l.scale;
        if (i + 1 < text.size())
            x += stbtt_GetCodepointKernAdvance(&info, cp, codepoint_at(text, i + 1)) * l.scale;
    }
    return bm;
}

// ---------------------------------------------------------------------------
// Blit
// ---------------------------------------------------------------------------
void blit_text(uint32_t* pixels, uint32_t stride_u32, uint32_t sw, uint32_t sh,
               const TextBitmap& bm, int x, int y, uint32_t rgb, uint8_t alpha) {
    if (!pixels || bm.w <= 0 || bm.h <= 0 || alpha == 0) return;
    const uint32_t cr = (rgb >> 16) & 0xFF, cg = (rgb >> 8) & 0xFF, cb = rgb & 0xFF;
    int x_begin = std::max(0, -x), x_end = std::min(bm.w, (int)sw - x);
    int y_begin = std::max(0, -y), y_end = std::min(bm.h, (int)sh - y);
    for (int by = y_begin; by < y_end; by++) {
        uint32_t* row = pixels + (size_t)(y + by) * stride_u32;
        const uint8_t* src = bm.alpha.data() + (size_t)by * bm.w;
        for (int bx = x_begin; bx < x_end; bx++) {
            uint32_t a = (uint32_t)src[bx] * alpha / 255;
            if (a == 0) continue;
            uint32_t& p = row[x + bx];
            if (a >= 255) { p = 0xFF000000u | (cr << 16) | (cg << 8) | cb; continue; }
            uint32_t pr = (p >> 16) & 0xFF, pg = (p >> 8) & 0xFF, pb = p & 0xFF;
            uint32_t nr = (cr * a + pr * (255 - a)) / 255;
            uint32_t ng = (cg * a + pg * (255 - a)) / 255;
            uint32_t nb = (cb * a + pb * (255 - a)) / 255;
            p = 0xFF000000u | (nr << 16) | (ng << 8) | nb;
        }
    }
}

